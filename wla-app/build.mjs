// Compiles the /wla-app JSX sources into one plain-JS bundle, app.js.
//
// The page used to ship @babel/standalone (~2.9MB) and React's development
// builds, then compile five files in the browser before anything rendered.
// Now the compile happens here instead.
//
//   node wla-app/build.mjs
//
// Run it after editing anything in wla-app/components/. The .jsx files are the
// source of truth; app.js is generated and should not be hand-edited.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { transformSync } from '@babel/core';

const here = dirname(fileURLToPath(import.meta.url));

// Order matters: sections.jsx defines the primitives the others close over.
const SOURCES = [
  'components/sections.jsx',
  'components/hero.jsx',
  'components/content.jsx',
  'components/closing.jsx',
  'components/app.jsx',
  'components/page.jsx',
];

const parts = SOURCES.map((rel) => {
  const code = readFileSync(join(here, rel), 'utf8');
  const { code: out } = transformSync(code, {
    filename: rel,
    presets: [['@babel/preset-react', { runtime: 'classic' }]],
    compact: false,
    babelrc: false,
    configFile: false,
  });
  // Each file ran as its own <script>, so keep them in separate scopes.
  return `/* ---- ${rel} ---- */\n(function () {\n${out}\n})();`;
});

const banner = `/* GENERATED by wla-app/build.mjs — do not edit.
   Source: ${SOURCES.join(', ')} */\n`;

writeFileSync(join(here, 'app.js'), banner + parts.join('\n\n') + '\n');
console.log('wrote wla-app/app.js from', SOURCES.length, 'sources');
